#!/usr/bin/env node
// Static mirror of the Lean law API, for the browser and anyone without a server.
//
//   node dashboard/build-lean-api.mjs           write dashboard/public/api/lean/
//   node dashboard/build-lean-api.mjs --check   exit 1 if the mirror on disk differs from what would be written
//
// Writes, from the SAME loader the MCP tools use (lib/lean-source.mjs):
//   api/lean/index.json              every law (summary), every lawset version, the source fingerprint
//   api/lean/laws/<law_id>.json      lean_law_get's result for that law
//   api/lean/laws/<law_id>@<v>.json  an archived version an older lawset pins (lean/registry/law-versions/)
//   api/lean/lawsets/<version>.json  lean_lawset_get's result for that release
//   api/lean/current.json            the current lawset
//   api/lean/scope.mjs               copy of lib/lean-scope.mjs (the out-of-scope rule) for lean-client.js
//   api/lean/lean-taxonomy.mjs       copy of lib/lean-taxonomy.mjs (the generated clade table scope.mjs imports)
//   api/lean/browser-check.mjs       copy of the generated lean/eliminate/browser-check.mjs (the evaluator)
//   api/lean/changes.json            lawset releases, newest first: CHANGELOG prose + bullets + a diff of the pins
//   api/lean/changes.xml             the same as an Atom feed (poll either; lean_changes(since_version) is the tool)
//   api/lean/capability/...          the LeanBio capability map: personas, use cases, grand questions, tool gaps
// The site's Cloudflare static hosting (dashboard/wrangler.jsonc, assets ./public) then serves GET /api/lean/...
// with no server.
//
// RULE for the Design Studio and every page: fetch laws from the API (the live sim-engine HTTP bridge if one
// is configured, else this /api/lean/ mirror) through dashboard/public/blueprint3d/lean-client.js. Never paste
// a law list into a page. lean/registry/check-exposed.mjs fails when this mirror is stale.
//
// Output is deterministic (no timestamps, no git commit beyond what the registry itself pins), so rebuilding
// unchanged sources leaves the files byte-identical and --check is meaningful.

import fs from 'node:fs';
import path from 'node:path';
import * as src from '../lib/lean-source.mjs';
// Open questions and failed theorems (lean/registry/open-questions/). Optional, so the mirror still builds in a
// checkout without the folder.
let openq = null;
try { openq = await import('../lean/registry/open-questions/openq-lib.mjs'); } catch { openq = null; }
// The LeanBio capability map (pipeline/leanbio/capability-map/). Optional, same reason: the mirror still builds in
// a checkout without the folder. It supplies its own mirror files, so this file holds none of its content.
let capmap = null;
try { capmap = await import('../pipeline/leanbio/capability-map/build.mjs'); } catch { capmap = null; }

const OQ_SCOPE =
  'Static mirror of lean/registry/open-questions/. An OPEN QUESTION is a question this project holds unsettled, ' +
  'with an arm per live position, each arm\'s evidence quoted from its primary source, and a belief `proportion` ' +
  'COMPUTED by pipeline/leanbio/belief.mjs rather than asserted. A proportion orders the arms; it is NOT a ' +
  'probability that an arm is true, and belief-params.json says plainly that its parameters are hand-set and not ' +
  'fitted. No arm of an open question is in any law set, and the guard in openq-lib.mjs refuses to accept a law ' +
  'that asserts one. A FAILED THEOREM is a statement this project tried and could not establish, kept with its ' +
  'reason so nobody reproposes it; `what_survives` says what is still true after the failure. READ `attempted`: a ' +
  'failed-theorem record with `attempted: false` was NEVER TRIED (the single Lean build lock was contended, or it ' +
  'was abandoned on cost, or withheld on purpose), so it is not a result about the statement at all and its ' +
  '`proof_status` says so; the counts report attempted and never-attempted separately for that reason. A ' +
  'NOT-CHECKABLE-IN-PRINCIPLE record is a fourth thing: sound, usually proved, but with no falsifiable direction ' +
  'over any design, so NO input would make it bind -- it carries no `missing_inputs`, because a list of them ' +
  'would read as a to-do and misstate the finding. Arms formalised in Lean are proved internally consistent and ' +
  'are NOT proved true of any organism.';

// The mirror is built from the local tree, never from a remote source (it IS what remotes fetch).
process.env.LEANBIO_REMOTE = 'off';
// Absolute base for Atom ids and links (the deployed mirror). Override when the site moves.
const SITE = process.env.LEANBIO_SITE_URL || src.DEFAULT_MIRROR;

export const OUT = path.join(import.meta.dirname, 'public', 'api', 'lean');

const SCOPE =
  'Static mirror generated by dashboard/build-lean-api.mjs from lib/lean-source.mjs, the same loader the MCP ' +
  'tools (lean_laws_list, lean_law_get, lean_lawset_get) use. A law\'s status is a registry decision, not a truth ' +
  'value; "proved" means a Lean kernel proof about a model, never that the model describes an organism. Laws ' +
  'absent here are unchecked, not satisfied. Evaluation (lean_check) is not mirrored: the browser runs ' +
  'blueprint3d/browser-check.mjs locally via lean-client.js.';

const safe = id => String(id).replace(/[^A-Za-z0-9._-]/g, '_');

// Strip values that change with the checkout rather than with the laws (fallback mode stamps HEAD).
function stable(o) {
  return JSON.parse(JSON.stringify(o, (k, v) => (k === 'module_hash' ? undefined : v)));
}

export function generate() {
  const reg = src.load({ fresh: true });
  const fp = src.sourceFingerprint();
  const files = {};
  const put = (rel, obj) => { files[rel] = JSON.stringify(obj, null, 1) + '\n'; };
  const list = src.listLaws({});
  put('index.json', {
    api: 'delphisci lean laws, static mirror',
    version: 1,
    origin: reg.origin,
    current_lawset: reg.current,
    lawsets: reg.lawsets.map(s => s.version),
    count: list.count,
    laws: list.laws.map(l => ({ ...l, href: `laws/${safe(l.law_id)}.json` })),
    endpoints: { law: 'laws/<law_id>.json', law_version: 'laws/<law_id>@<version>.json', lawset: 'lawsets/<version>.json', current: 'current.json', changes: 'changes.json', changes_atom: 'changes.xml', open_questions: 'open-questions.json', capability: 'capability/index.json' },
    scope: SCOPE,
    source_fingerprint: fp,
  });
  for (const l of reg.laws) put(`laws/${safe(l.law_id)}.json`, stable({ ...src.getLaw(l.law_id), scope_note: SCOPE }));
  // Archived versions older lawsets pin: laws/<law_id>@<version>.json
  for (const v of Object.values(reg.versions || {})) put(`laws/${safe(v.law_id)}@${safe(v.version)}.json`, stable({ ...src.getLaw(v.law_id, v.version), scope_note: SCOPE }));
  for (const s of reg.lawsets) put(`lawsets/${safe(s.version)}.json`, src.getLawset(s.version));
  put('current.json', src.getLawset('current'));
  const md = fs.existsSync(path.join(src.REGISTRY_DIR, 'CHANGELOG.md')) ? fs.readFileSync(path.join(src.REGISTRY_DIR, 'CHANGELOG.md'), 'utf8') : '';
  const feed = src.changesFeed(src.parseLawsetChangelog(md), reg.lawsets);
  put('changes.json', feed);
  files['changes.xml'] = atom(feed);
  // The scope rule, verbatim, so the browser client computes 'out-of-scope' with the same code as lean_check.
  // The generated checker itself, so the browser evaluates with the SAME build the lawsets were released against.
  // dashboard/public/blueprint3d/browser-check.mjs is copied by another thread's build-graph.mjs and can lag; this
  // copy is regenerated here and covered by --check, so lean-client.js prefers it.
  files['browser-check.mjs'] = fs.readFileSync(path.join(src.ROOT, 'lean', 'eliminate', 'browser-check.mjs'), 'utf8').replace(/\r\n/g, '\n');
  files['scope.mjs'] = '// GENERATED by dashboard/build-lean-api.mjs: a verbatim copy of lib/lean-scope.mjs. Do not edit.\n' +
    fs.readFileSync(path.join(src.ROOT, 'lib', 'lean-scope.mjs'), 'utf8').replace(/\r\n/g, '\n');
  // scope.mjs imports the generated clade table, so the browser needs it beside the copy or the module
  // fails to resolve at load. Shipped verbatim for the same reason scope.mjs is: one implementation.
  files['lean-taxonomy.mjs'] = '// GENERATED by lean/registry/build-taxonomy.mjs, copied here by dashboard/build-lean-api.mjs. Do not edit.\n' +
    fs.readFileSync(path.join(src.ROOT, 'lib', 'lean-taxonomy.mjs'), 'utf8').replace(/\r\n/g, '\n');
  // Open questions, failed theorems and requirement records (lean/registry/open-questions/). A law set says what
  // this project holds PROVED; these say what it holds UNSETTLED, and what it tried and could not establish. Both
  // belong in the static API for the same reason: a page must never carry its own copy of either list.
  //   api/lean/open-questions.json            the summary (every question, its arms, its computed proportion)
  //   api/lean/open-questions/<question_id>.json   one full record, with evidence quotes and what would settle it
  //   api/lean/failed-theorems/<failure_id>.json   one full failed-theorem record
  if (openq) {
    const oqreg = openq.load();
    const s = openq.summary({ reg: oqreg });
    put('open-questions.json', {
      api: 'delphisci lean open questions, static mirror', version: 1,
      ...s,
      endpoints: { question: 'open-questions/<question_id>.json', failed_theorem: 'failed-theorems/<failure_id>.json',
        requirement: 'requirements/<requirement_id>.json', not_checkable: 'not-checkable/<not_checkable_id>.json' },
      scope: OQ_SCOPE, source_fingerprint: fp,
    });
    for (const q of oqreg.questions) put(`open-questions/${safe(q.question_id)}.json`, { ...q, scope_note: OQ_SCOPE });
    for (const f of oqreg.failed) put(`failed-theorems/${safe(f.failure_id)}.json`, { ...f, scope_note: OQ_SCOPE });
    for (const r of oqreg.requirements) put(`requirements/${safe(r.requirement_id)}.json`, { ...r, scope_note: OQ_SCOPE });
    for (const n of oqreg.notCheckable || []) put(`not-checkable/${safe(n.not_checkable_id)}.json`, { ...n, scope_note: OQ_SCOPE });
  }
  // The LeanBio capability map (pipeline/leanbio/capability-map/). A law set says what this project holds proved;
  // the open questions say what it holds unsettled; the capability map says WHO could use any of it, for WHAT, and
  // which tools do not exist yet. Same rule as the other two: a page must never carry its own copy of the list.
  //   api/lean/capability/index.json                    counts, the formalisable/empirical line, every id
  //   api/lean/capability/personas.json                 who could use Lean for Bio, and the tools each needs
  //   api/lean/capability/use-cases.json                one row per job: the tool sequence today, and what is missing
  //   api/lean/capability/grand-questions.json          the formalisable core and the empirical remainder, per question
  //   api/lean/capability/grand-questions/<id>.json     one question in full, with its citations resolved
  //   api/lean/capability/tool-gap.json                 the ranked gap list, and what is deliberately absent
  //   api/lean/capability/citations.json                the fetched literature behind the grand questions
  //   api/lean/capability/schema.json                   the JSON Schema the four enumerations validate against
  // The map's files are its own, generated by its own build.mjs, so this mirror cannot restate them differently.
  if (capmap) {
    for (const [rel, text] of Object.entries(capmap.mirrorFiles())) files[`capability/${rel}`] = text;
  }
  return files;
}

const xml = t => String(t ?? '').replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const day = d => (/^\d{4}-\d{2}-\d{2}$/.test(d || '') ? `${d}T00:00:00Z` : '1970-01-01T00:00:00Z');
// Atom 1.0 feed of lawset releases. Deterministic: <updated> is the newest release date, not the build time.
export function atom(feed) {
  const entry = e => {
    const d = e.diff || {};
    const lines = [
      ...(d.added || []).map(x => `added ${x.law_id} ${x.version}${x.status ? ` (${x.status})` : ''}`),
      ...(d.removed || []).map(x => `removed ${x.law_id} ${x.version}`),
      ...(d.version || []).map(x => `${x.law_id} ${x.from} -> ${x.to}`),
      ...(d.status || []).map(x => `${x.law_id} status ${x.from} -> ${x.to}`),
    ];
    const body = `${e.summary || ''}${lines.length ? `\n\nChanges (from the lawset pins):\n- ${lines.join('\n- ')}` : '\n\nNo law changes.'}`;
    return `  <entry>
    <id>${xml(SITE)}lawsets/${xml(e.version)}.json</id>
    <title>LeanBio lawset ${xml(e.version)}: ${xml(e.title)}</title>
    <updated>${day(e.date)}</updated>
    <link rel="alternate" type="application/json" href="${xml(SITE)}${xml(e.href)}"/>
    <content type="text">${xml(body)}</content>
  </entry>`;
  };
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by dashboard/build-lean-api.mjs from lean/registry/CHANGELOG.md and lawsets/. Do not edit. -->
<feed xmlns="http://www.w3.org/2005/Atom">
  <id>${xml(SITE)}changes.xml</id>
  <title>delphisci LeanBio lawset changes</title>
  <subtitle>Releases of the versioned Lean law registry. Current lawset: ${xml(feed.current_lawset)}. JSON: changes.json; MCP: lean_changes(since_version).</subtitle>
  <updated>${day(feed.entries[0]?.date)}</updated>
  <link rel="self" type="application/atom+xml" href="${xml(SITE)}changes.xml"/>
  <link rel="alternate" type="application/json" href="${xml(SITE)}changes.json"/>
  <author><name>delphisci law registry</name></author>
${feed.entries.map(entry).join('\n')}
</feed>
`;
}

function onDisk() {
  const out = {};
  const walk = d => { if (!fs.existsSync(d)) return; for (const e of fs.readdirSync(d, { withFileTypes: true })) {
    const p = path.join(d, e.name); if (e.isDirectory()) walk(p); else out[path.relative(OUT, p).replace(/\\/g, '/')] = fs.readFileSync(p, 'utf8'); } };
  walk(OUT);
  return out;
}

// Differences between the mirror on disk and a fresh generation: [{file, why}].
export function diff() {
  const want = generate(), have = onDisk();
  const d = [];
  // Normalise BOTH sides. Only the on-disk side used to be normalised, which is wrong whenever a
  // generated file is passed through from a source file rather than serialised here: on a Windows
  // checkout git hands that source CRLF, the CRLF travels into `want`, and the gate reports the
  // mirror permanently stale while write() keeps rewriting a byte-identical file. Caught on the PR
  // clone, where capability/schema.json pinned check-exposed red. Line endings are not content.
  const lf = t => String(t).replace(/\r\n/g, '\n');
  for (const f of Object.keys(want)) if (have[f] === undefined) d.push({ file: f, why: 'missing' }); else if (lf(have[f]) !== lf(want[f])) d.push({ file: f, why: 'stale' });
  for (const f of Object.keys(have)) if (want[f] === undefined) d.push({ file: f, why: 'orphan (no such law/lawset any more)' });
  return d;
}

export function write() {
  const want = generate();
  const have = onDisk();
  for (const f of Object.keys(have)) if (want[f] === undefined) fs.rmSync(path.join(OUT, f));
  for (const [f, text] of Object.entries(want)) {
    const p = path.join(OUT, f);
    fs.mkdirSync(path.dirname(p), { recursive: true });
    if (have[f] !== text) fs.writeFileSync(p, text);
  }
  return Object.keys(want).length;
}

if (import.meta.url === `file:///${process.argv[1]?.replace(/\\/g, '/')}` || import.meta.url === `file://${process.argv[1]}`) {
  if (process.argv.includes('--check')) {
    const d = diff();
    if (d.length) { console.error(`static mirror dashboard/public/api/lean/ is stale (${d.length} files):`); for (const x of d.slice(0, 20)) console.error(`  ${x.why}: ${x.file}`); console.error('fix: node dashboard/build-lean-api.mjs'); process.exit(1); }
    console.log('static mirror up to date');
  } else {
    const n = write();
    console.log(`wrote ${n} files to ${path.relative(process.cwd(), OUT) || OUT}`);
  }
}
