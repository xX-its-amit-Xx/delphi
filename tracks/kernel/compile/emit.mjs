// assembly protocols

export function opentrons(plan, file) {
  const parts = plan.slots.filter((s) => s.sequence);
  const p = [];
  p.push('# Golden Gate assembly, generated by the DELPHI kernel. NOT RUN ON HARDWARE.');
  p.push('# Review every volume and every deck position before you put this on a robot.');
  p.push(`# Construct: ${plan.module}. Slots with a sequence from a primary record: ${parts.length} of ${plan.slots.length}.`);
  p.push(`# Open slots are NOT in this protocol; they cannot be pipetted until a sequence exists for them.`);
  p.push('from opentrons import protocol_api');
  p.push('');
  p.push('metadata = {"protocolName": "DELPHI Golden Gate: ' + plan.module + '", "author": "DELPHI kernel", "apiLevel": "2.19"}');
  p.push('');
  p.push('def run(protocol: protocol_api.ProtocolContext):');
  p.push('    tips = protocol.load_labware("opentrons_96_filtertiprack_20ul", 1)');
  p.push('    parts_plate = protocol.load_labware("biorad_96_wellplate_200ul_pcr", 2)');
  p.push('    rxn_plate = protocol.load_labware("biorad_96_wellplate_200ul_pcr", 3)');
  p.push('    reagents = protocol.load_labware("opentrons_24_tuberack_nest_1.5ml_snapcap", 4)');
  p.push('    p20 = protocol.load_instrument("p20_single_gen2", "right", tip_racks=[tips])');
  p.push('    tc = protocol.load_module("thermocyclerModuleV2")');
  p.push('');
  p.push('    mix = reagents.wells_by_name()["A1"]   # T4 ligase buffer + BsaI-HFv2 + T4 DNA ligase');
  p.push('    water = reagents.wells_by_name()["A2"]');
  p.push('    rxn = rxn_plate.wells_by_name()["A1"]');
  p.push('');
  p.push('    p20.transfer(2.0, mix, rxn, new_tip="always")');
  parts.forEach((s, i) => {
    const well = `${'ABCDEFGH'[i % 8]}${Math.floor(i / 8) + 1}`;
    p.push(`    p20.transfer(1.0, parts_plate.wells_by_name()["${well}"], rxn, new_tip="always")   # ${s.id} (${s.role}, ${s.sequence.length} bp)`);
  });
  p.push(`    p20.transfer(${Math.max(1, 20 - 2 - parts.length)}.0, water, rxn, new_tip="always")`);
  p.push('');
  p.push('    tc.close_lid()');
  p.push('    tc.set_lid_temperature(105)');
  p.push('    tc.execute_profile(steps=[{"temperature": 37, "hold_time_minutes": 5},');
  p.push('                              {"temperature": 16, "hold_time_minutes": 5}], repetitions=30, block_max_volume=20)');
  p.push('    tc.set_block_temperature(60, hold_time_minutes=5)');
  p.push('    tc.set_block_temperature(10)');
  p.push('    tc.open_lid()');
  p.push('    protocol.comment("Transform 2 uL into chemically competent E. coli ' + plan.host + ' by hand.")');
  return W(file, p.join('\n') + '\n');
}

export function autoprotocol(plan, file) {
  const parts = plan.slots.filter((s) => s.sequence);
  const refs = { reaction: { new: '96-pcr', store: { where: 'cold_4' } }, master_mix: { new: 'micro-1.5', store: { where: 'cold_20' } }, parts_plate: { new: '96-pcr', store: { where: 'cold_20' } } };
  const transfers = [{ from: 'master_mix/0', to: 'reaction/0', volume: '2.0:microliter', mix_after: false }];
  parts.forEach((s, i) => transfers.push({ from: `parts_plate/${i}`, to: 'reaction/0', volume: '1.0:microliter', mix_after: false, x_part: s.id }));
  const protocol = {
    $comment: `Golden Gate assembly of ${plan.module}, generated by the DELPHI kernel. Not executed. ${parts.length} of ${plan.slots.length} slots have a sequence from a primary record; open slots are absent from this protocol by design.`,
    refs,
    instructions: [
      { op: 'pipette', groups: [{ transfer: transfers }] },
      { op: 'thermocycle', object: 'reaction', volume: '20:microliter', dataref: 'golden_gate',
        groups: [{ cycles: 30, steps: [{ temperature: '37:celsius', duration: '5:minute' }, { temperature: '16:celsius', duration: '5:minute' }] },
                 { cycles: 1, steps: [{ temperature: '60:celsius', duration: '5:minute' }] }] },
      { op: 'incubate', object: 'reaction', where: 'cold_4', duration: '10:minute', shaking: false },
    ],
  };
  return W(file, JSON.stringify(protocol, null, 2) + '\n');
}

