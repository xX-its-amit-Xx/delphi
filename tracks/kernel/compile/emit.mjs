// The back ends. Each one turns a mapped netlist into a file somebody can use, and each one refuses
// rather than inventing a number or a base.
//
//   genbank()      annotated construct. Filled slots carry their sequence and the record it came from;
//                  open slots are real GenBank `assembly_gap` features, so the file says out loud what
//                  it does not have instead of looking finished.
//   fasta()        refused while any slot is open: a FASTA has nowhere to put "unknown".
//   sbml()         refused unless every gate has the parameters an ODE needs, and names the missing
//                  ones per gate. This refusal is the useful output: it is the shortest list of
//                  measurements that would make the circuit simulable.
//   opentrons()    liquid-handling steps for Golden Gate assembly of the slots that exist.
//   autoprotocol() the same run in Autoprotocol's vocabulary.
//   nanopubDraft() unsigned TriG, one per missing measurement, ready for a wet-lab result to be
//                  written back into the registry. UNSIGNED: signing is the key owner's decision.
//   justify()      the build log as linked data: every chosen part back to the record that justified it.

import fs from 'node:fs';
import path from 'node:path';

const W = (file, text) => { fs.mkdirSync(path.dirname(file), { recursive: true }); fs.writeFileSync(file, text); return { path: file, bytes: Buffer.byteLength(text) }; };

// Dates come from the registry's own version stamp, never from the clock. An artifact that changes
// its bytes every midnight cannot be reproduced, and its hash in the build node would mean nothing.
const stampOf = (plan) => plan?.stamp ?? process.env.DELPHI_STAMP ?? '1970-01-01';
const GB_DATE = (plan) => {
  const [y, m, d] = stampOf(plan).split('-');
  return `${d}-${['JAN','FEB','MAR','APR','MAY','JUN','JUL','AUG','SEP','OCT','NOV','DEC'][Number(m) - 1]}-${y}`;
};

// ---------------------------------------------------------------------------------------------------

export function genbank(plan, file) {
  const slots = plan.slots;
  const lines = [];
  let pos = 1;
  const feats = [];
  let seq = '';

  for (const s of slots) {
    if (s.sequence) {
      const start = pos, end = pos + s.sequence.length - 1;
      seq += s.sequence;
      pos = end + 1;
      feats.push({ key: s.gbkey ?? 'misc_feature', range: `${start}..${end}`, quals: [
        ['label', s.id], ['function', s.role],
        ['note', `sequence from ${s.sequence_source_citation ?? s.sequence_source ?? 'unstated record'}`],
        ['note', `quoted as: ${s.sequence_quote ?? ''}`],
        ['note', `located at: ${s.sequence_where ?? ''}`],
      ].filter(([, v]) => v !== undefined && v !== '') });
    } else {
      // A gap of unknown length, which is exactly what this is.
      const start = pos, end = pos + 99; // 100 n's: GenBank gaps need a run, and the length is declared unknown
      seq += 'n'.repeat(100);
      pos = end + 1;
      feats.push({ key: 'assembly_gap', range: `${start}..${end}`, quals: [
        ['estimated_length', 'unknown'], ['gap_type', 'unknown'],
        ['label', s.id], ['function', s.role],
        ['note', `OPEN SLOT, not a sequence: ${s.sequence_open_because ?? 'no primary record read'}`],
        ['note', `would be filled by: ${s.sequence_would_be_filled_by ?? 'unknown record'}`],
      ] });
    }
  }

  const filled = slots.filter((s) => s.sequence).length;
  lines.push(`LOCUS       ${plan.module.padEnd(16).slice(0, 16)} ${seq.length} bp    DNA     linear   SYN ${GB_DATE(plan)}`);
  lines.push(`DEFINITION  ${plan.module}: ${plan.gates.length} transcriptional gate(s) compiled by the DELPHI kernel.`);
  lines.push(`ACCESSION   .`);
  lines.push(`VERSION     .`);
  lines.push(`KEYWORDS    DELPHI kernel; compiled construct; ${filled} of ${slots.length} slots filled.`);
  lines.push(`SOURCE      synthetic construct`);
  lines.push(`  ORGANISM  synthetic construct`);
  lines.push(`COMMENT     Generated by tracks/kernel/compile/compile.mjs. This is a DESIGN, not a verified`);
  lines.push(`            construct: nothing here has been built or sequenced. ${slots.length - filled} slot(s) are`);
  lines.push(`            assembly_gap features because no primary record for their sequence was read; the`);
  lines.push(`            run's justification graph names the record that would fill each one.`);
  lines.push(`            Target host: ${plan.host}. Kernel build: ${plan.build_id ?? 'unminted'}.`);
  lines.push(`FEATURES             Location/Qualifiers`);
  lines.push(`     source          1..${seq.length}`);
  lines.push(`                     /organism="synthetic construct"`);
  lines.push(`                     /mol_type="other DNA"`);
  for (const f of feats) {
    lines.push(`     ${f.key.padEnd(15).slice(0, 15)} ${f.range}`);
    for (const [k, v] of f.quals) lines.push(`                     /${k}=${/^\d+$/.test(String(v)) ? v : `"${String(v).replace(/"/g, "'")}"`}`);
  }
  lines.push('ORIGIN');
  for (let i = 0; i < seq.length; i += 60) {
    const chunk = seq.slice(i, i + 60).match(/.{1,10}/g).join(' ');
    lines.push(`${String(i + 1).padStart(9)} ${chunk}`);
  }
  lines.push('//');
  return W(file, lines.join('\n') + '\n');
}

export function fasta(plan, file) {
  const open = plan.slots.filter((s) => !s.sequence);
  if (open.length) return { refused: [`a FASTA cannot represent an unknown base run honestly: ${open.length} of ${plan.slots.length} slot(s) have no sequence from a primary record (${open.map((s) => s.id).join(', ')})`] };
  const seq = plan.slots.map((s) => s.sequence).join('');
  const body = seq.match(/.{1,70}/g).join('\n');
  return W(file, `>${plan.module} DELPHI-compiled construct, ${seq.length} bp, all ${plan.slots.length} slots from primary records\n${body}\n`);
}

// ---------------------------------------------------------------------------------------------------
// SBML: a Hill function per gate. Refused unless every gate has every parameter.

const HILL_PARAMS = [
  ['ymin', 'output_off_REU', "the gate's output when fully repressed"],
  ['ymax', 'output_on_REU', "the gate's output when not repressed"],
  ['K', 'threshold_REU', 'the input at which the output is half-maximal'],
  ['n', 'hill_coefficient', 'the cooperativity of repression'],
];

export function sbml(plan, file) {
  const missing = [];
  for (const g of plan.gates) {
    if (g.kind === 'OR') continue; // tandem promoters, no repressor, no Hill function of its own
    for (const [p, quantity, meaning] of HILL_PARAMS) {
      if (g.params?.[quantity] === undefined) missing.push({ gate: g.output, repressor: g.repressor, parameter: p, quantity, meaning });
    }
  }
  if (missing.length) {
    return { refused: [`an ODE model needs ${HILL_PARAMS.length} parameters per gate and ${missing.length} are not in any record that was read`], missing };
  }
  const species = [...new Set([...plan.inputs, ...plan.gates.map((g) => g.output)])];
  const x = [];
  x.push('<?xml version="1.0" encoding="UTF-8"?>');
  x.push('<sbml xmlns="http://www.sbml.org/sbml/level3/version2/core" level="3" version="2">');
  x.push(`  <model id="${plan.module}" name="${plan.module} (DELPHI-compiled)" substanceUnits="dimensionless" timeUnits="hour" extentUnits="dimensionless">`);
  x.push('    <notes><body xmlns="http://www.w3.org/1999/xhtml"><p>Every parameter below is quoted from a primary record; see the run justification graph.</p></body></notes>');
  x.push('    <listOfCompartments><compartment id="cell" spatialDimensions="3" size="1" constant="true"/></listOfCompartments>');
  x.push('    <listOfSpecies>');
  for (const s of species) x.push(`      <species id="${s}" compartment="cell" initialAmount="0" hasOnlySubstanceUnits="true" boundaryCondition="${plan.inputs.includes(s) ? 'true' : 'false'}" constant="false"/>`);
  x.push('    </listOfSpecies>');
  x.push('    <listOfParameters>');
  for (const g of plan.gates.filter((g) => g.kind !== 'OR')) for (const [p, q] of HILL_PARAMS) x.push(`      <parameter id="${p}_${g.output}" value="${g.params[q]}" constant="true"/>`);
  x.push('    </listOfParameters>');
  x.push('    <listOfRules>');
  for (const g of plan.gates.filter((g) => g.kind !== 'OR')) {
    const input = g.inputs.length > 1 ? g.inputs.join(' + ') : g.inputs[0];
    x.push(`      <assignmentRule variable="${g.output}">`);
    x.push('        <math xmlns="http://www.w3.org/1998/Math/MathML">');
    x.push(`          <apply><plus/><ci>ymin_${g.output}</ci><apply><divide/><apply><minus/><ci>ymax_${g.output}</ci><ci>ymin_${g.output}</ci></apply><apply><plus/><cn>1</cn><apply><power/><apply><divide/><ci>${input.split(' + ')[0]}</ci><ci>K_${g.output}</ci></apply><ci>n_${g.output}</ci></apply></apply></apply></apply>`);
    x.push('        </math>');
    x.push('      </assignmentRule>');
  }
  x.push('    </listOfRules>');
  x.push('  </model>');
  x.push('</sbml>');
  return W(file, x.join('\n') + '\n');
}

