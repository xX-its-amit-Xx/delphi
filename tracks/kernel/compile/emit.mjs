// nanopublication drafts: one per measurement the compiler needed and could not find. UNSIGNED.

export function nanopubDrafts(missing, dir, plan) {
  const out = [];
  for (const [i, m] of missing.entries()) {
    const id = `${plan.module}-${m.gate ?? m.id ?? i}-${m.parameter ?? m.quantity ?? 'value'}`.replace(/[^\w-]/g, '-').toLowerCase();
    const trig = `# UNSIGNED DRAFT. A template for a wet-lab result, not a result.
# Nothing here has been measured. Fill measuredValue, the conditions and the provenance, then have the
# key owner decide whether to sign and publish it. Do not publish with a placeholder in it.
@prefix this: <http://purl.org/nanopub/temp/${id}#> .
@prefix sub: <http://purl.org/nanopub/temp/${id}#> .
@prefix np: <http://www.nanopub.org/nschema#> .
@prefix dct: <http://purl.org/dc/terms/> .
@prefix prov: <http://www.w3.org/ns/prov#> .
@prefix sio: <http://semanticscience.org/resource/> .
@prefix xsd: <http://www.w3.org/2001/XMLSchema#> .
@prefix delphi: <https://w3id.org/delphi/resource/> .

sub:Head {
  this: np:hasAssertion sub:assertion ;
    np:hasProvenance sub:provenance ;
    np:hasPublicationInfo sub:pubinfo ;
    a np:Nanopublication .
}

sub:assertion {
  delphi:${m.gate ?? m.id ?? 'part'} a delphi:GeneticPart ;
    dct:identifier "${m.repressor ?? m.id ?? m.gate ?? ''}" ;
    delphi:hasMeasurement sub:measurement .

  sub:measurement a sio:SIO_000976 ;
    delphi:quantity "${m.quantity ?? m.parameter}" ;
    delphi:meaning "${(m.meaning ?? '').replace(/"/g, "'")}" ;
    delphi:measuredValue "FILL-IN"^^xsd:double ;
    delphi:unit "FILL-IN" ;
    delphi:host "FILL-IN" ;
    delphi:strain "FILL-IN" ;
    delphi:medium "FILL-IN" ;
    delphi:temperatureC "FILL-IN"^^xsd:double ;
    delphi:referenceStandard "FILL-IN" .
}

sub:provenance {
  sub:assertion prov:wasDerivedFrom <FILL-IN-the-record-or-run-that-measured-it> ;
    dct:description "Needed by the DELPHI kernel to compile ${plan.module}: without it the ${m.parameter ?? m.quantity} of this gate is unknown and the kernel refuses to emit a predictive model." .
}

sub:pubinfo {
  this: dct:created "${stampOf(plan)}"^^xsd:date ;
    dct:creator <FILL-IN-an-orcid> ;
    dct:rights <https://creativecommons.org/licenses/by/4.0/> ;
    delphi:kernelBuild "${plan.build_id ?? 'unminted'}" ;
    delphi:status "UNSIGNED DRAFT, placeholder values, do not publish" .
}
`;
    out.push(W(path.join(dir, `${id}.trig`), trig));
  }
  return out;
}

// ---------------------------------------------------------------------------------------------------
// the justification graph: every part and every number back to the record that justified it

export function justify(plan, kernelNodes, file) {
  const g = {
    '@context': {
      delphi: 'https://w3id.org/delphi/resource/',
      prov: 'http://www.w3.org/ns/prov#',
      dct: 'http://purl.org/dc/terms/',
      quote: 'delphi:quote', where: 'delphi:where', quantity: 'delphi:quantity', value: 'delphi:value',
    },
    '@id': `delphi:build/${plan.module}/${plan.build_id ?? 'unminted'}`,
    '@type': 'prov:Entity',
    'dct:title': `${plan.module}: what justified every choice`,
    'dct:created': stampOf(plan),
    'delphi:kernelBuild': plan.build_id ?? null,
    'delphi:targetHost': plan.host,
    'delphi:readMe': 'Each slot below names the record that put its sequence or its number there. A slot with "open": true has no record and the compiler refused to fill it. Nothing in this graph is a claim about the construct working; it is a claim about where each design decision came from.',
    'delphi:slots': plan.slots.map((s) => ({
      '@id': `delphi:part/${s.id}`,
      'delphi:role': s.role,
      open: !s.sequence,
      'delphi:sequenceLength': s.sequence ? s.sequence.length : null,
      'prov:wasDerivedFrom': s.sequence_source_citation ?? s.sequence_would_be_filled_by ?? null,
      quote: s.sequence_quote ?? null,
      where: s.sequence_where ?? null,
      'delphi:openBecause': s.sequence ? null : s.sequence_open_because,
    })),
    'delphi:gates': plan.gates.map((g2) => ({
      '@id': `delphi:gate/${g2.output}`, 'delphi:kind': g2.kind, 'delphi:repressor': g2.repressor ?? null,
      'delphi:inputs': g2.inputs, 'delphi:parameters': g2.params ?? {},
    })),
    'delphi:verdicts': kernelNodes.filter((n) => n.type === 'verdict').map((v) => ({
      '@id': `delphi:verdict/${v.id}`, 'delphi:law': v.law_name, 'delphi:label': v.label,
      'delphi:result': v.result, 'delphi:detail': v.detail, 'prov:used': v.facts,
    })),
    'delphi:facts': kernelNodes.filter((n) => n.type === 'fact').map((f) => ({
      '@id': `delphi:fact/${f.id}`, quantity: f.quantity, value: f.value, 'delphi:unit': f.unit,
      'delphi:conditions': f.conditions, 'prov:wasDerivedFrom': f.evidence,
    })),
    'delphi:evidence': kernelNodes.filter((n) => n.type === 'evidence').map((e) => ({
      '@id': `delphi:evidence/${e.id}`, 'delphi:kind': e.kind, 'dct:identifier': e.ref, quote: e.quote, where: e.where,
    })),
    'delphi:refusals': kernelNodes.filter((n) => n.type === 'refusal').map((r) => ({
      '@id': `delphi:refusal/${r.id}`, 'delphi:what': r.what, 'delphi:because': r.because,
    })),
  };
  return W(file, JSON.stringify(g, null, 1) + '\n');
}

export default { genbank, fasta, sbml, opentrons, autoprotocol, nanopubDrafts, justify };
